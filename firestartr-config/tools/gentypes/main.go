package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type schema struct {
	Title      string               `json:"title"`
	Type       string               `json:"type"`
	Properties map[string]*property `json:"properties"`
	Required   []string             `json:"required"`
}

type property struct {
	Type       string               `json:"type"`
	Properties map[string]*property `json:"properties"`
	Items      *property            `json:"items"`
	Enum       []string             `json:"enum"`
	Required   []string             `json:"required"`
}

type typeDef struct {
	Name   string
	Fields []fieldDef
}

type fieldDef struct {
	Name     string
	Type     string
	TagName  string
	Required bool
}

var (
	propNameOverrides = map[string]string{
		"type": "PlatformType",
		"url":  "Url",
	}
	topTypeNames = map[string]string{
		"apps":              "FirestartrApp",
		"docker_registries": "Registry",
		"helm_repositories": "Repository",
		"platforms":         "Platform",
	}
	nestedTypeNames = map[string]map[string]string{
		"apps": {
			"services": "FirestartrService",
		},
		"docker_registries": {
			"base_paths": "BasePaths",
		},
		"platforms": {
			"allowedClaims": "AllowedClaim",
		},
	}
)

func main() {
	base := filepath.Join("testdata", "dot-firestartr", "v3.2.0")
	contracts := []string{"apps", "docker_registries", "helm_repositories", "platforms"}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by tools/gentypes; DO NOT EDIT.\n\n")
	buf.WriteString("package main\n\n")

	typeDefs := []typeDef{}
	var authEnum []string

	for _, c := range contracts {
		b, err := os.ReadFile(filepath.Join(base, c+".schema.json"))
		if err != nil {
			fail(err)
		}
		var s schema
		if err := json.Unmarshal(b, &s); err != nil {
			fail(fmt.Errorf("%s: %w", c, err))
		}
		defs, enum := collectTypes(c, &s)
		typeDefs = append(typeDefs, defs...)
		if c == "docker_registries" && len(enum) > 0 {
			authEnum = append([]string{}, enum...)
		}
	}

	if len(authEnum) > 0 {
		buf.WriteString("type AuthStrategy string\n\n")
		buf.WriteString("const (\n")
		for _, v := range authEnum {
			buf.WriteString(fmt.Sprintf("\t%s AuthStrategy = %q\n", authConstName(v), v))
		}
		buf.WriteString(")\n\n")
	}

	seen := map[string]bool{}
	for _, td := range typeDefs {
		if seen[td.Name] {
			continue
		}
		seen[td.Name] = true
		emitType(&buf, td)
	}

	out, err := format.Source(buf.Bytes())
	if err != nil {
		_ = os.WriteFile("types_gen.go", buf.Bytes(), 0o644)
		fail(fmt.Errorf("format: %w", err))
	}
	if err := os.WriteFile("types_gen.go", out, 0o644); err != nil {
		fail(err)
	}
}

func collectTypes(contract string, s *schema) ([]typeDef, []string) {
	defs := []typeDef{}
	authEnum := []string{}
	topName := topTypeNames[contract]
	if topName == "" {
		topName = exportName(contract)
	}

	nested := nestedTypeNames[contract]
	for _, pk := range sortedKeys(s.Properties) {
		p := s.Properties[pk]
		if nName, ok := nested[pk]; ok {
			if p.Type == "object" {
				defs = append(defs, buildType(nName, p, contract))
			} else if p.Type == "array" && p.Items != nil && p.Items.Type == "object" {
				defs = append(defs, buildType(nName, p.Items, contract))
			}
		}
		if pk == "auth_strategy" && len(p.Enum) > 0 {
			authEnum = append([]string{}, p.Enum...)
		}
	}

	defs = append(defs, buildType(topName, &property{Type: "object", Properties: s.Properties, Required: s.Required}, contract))
	return defs, authEnum
}

func buildType(name string, p *property, contract string) typeDef {
	requiredSet := map[string]bool{}
	for _, r := range p.Required {
		requiredSet[r] = true
	}
	td := typeDef{Name: name}
	for _, k := range sortedKeys(p.Properties) {
		child := p.Properties[k]
		fd := fieldDef{
			Name:     goFieldName(k),
			TagName:  k,
			Required: requiredSet[k],
			Type:     goType(contract, k, child),
		}
		td.Fields = append(td.Fields, fd)
	}
	return td
}

func goType(contract, prop string, p *property) string {
	switch p.Type {
	case "string":
		if prop == "auth_strategy" && len(p.Enum) > 0 {
			return "AuthStrategy"
		}
		return "string"
	case "boolean":
		return "bool"
	case "array":
		if p.Items == nil {
			return "[]interface{}"
		}
		if p.Items.Type == "string" {
			return "[]string"
		}
		if p.Items.Type == "object" {
			if nName, ok := nestedTypeNames[contract][prop]; ok {
				return "[]" + nName
			}
			return "[]map[string]interface{}"
		}
		return "[]interface{}"
	case "object":
		if nName, ok := nestedTypeNames[contract][prop]; ok {
			return nName
		}
		return "map[string]interface{}"
	default:
		return "interface{}"
	}
}

func goFieldName(prop string) string {
	if o, ok := propNameOverrides[prop]; ok {
		return o
	}
	parts := strings.Split(prop, "_")
	if len(parts) == 1 {
		// already camelCase or simple word
		if prop == "" {
			return ""
		}
		return strings.ToUpper(prop[:1]) + prop[1:]
	}
	for i, p := range parts {
		if p == "" {
			continue
		}
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	return strings.Join(parts, "")
}

func exportName(s string) string {
	parts := strings.Split(s, "_")
	for i, p := range parts {
		if p == "" {
			continue
		}
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	return strings.Join(parts, "")
}

func authConstName(v string) string {
	switch v {
	case "aws_oidc":
		return "AuthStrategyAWSOIDC"
	case "azure_oidc":
		return "AuthStrategyAzureOIDC"
	case "generic":
		return "AuthStrategyGeneric"
	case "ghcr":
		return "AuthStrategyGHCR"
	case "dockerhub":
		return "AuthStrategyDockerHub"
	case "none":
		return "AuthStrategyNone"
	default:
		return "AuthStrategy" + exportName(v)
	}
}

func emitType(buf *bytes.Buffer, td typeDef) {
	buf.WriteString(fmt.Sprintf("type %s struct {\n", td.Name))
	for _, f := range td.Fields {
		tag := f.TagName
		if !f.Required {
			tag += ",omitempty"
		}
		buf.WriteString(fmt.Sprintf("\t%s %s `yaml:\"%s\" json:\"%s\"`\n", f.Name, f.Type, tag, tag))
	}
	buf.WriteString("}\n\n")
}

func sortedKeys(m map[string]*property) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
